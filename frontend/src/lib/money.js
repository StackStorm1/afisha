// Money из openapi.yaml — строка с двумя знаками после точки, например "2000.00".
// Math.round округляет половину вверх: toMoney(2.005) даёт "2.01".
// db-schema.md §3.5 требует банковского округления, к чётному ("2.00"), —
// оно здесь не реализовано. На моках расхождение не проявляется: базовая
// цена всегда целое число рублей, а множители зон (1 и 0.6) оставляют её
// целой, так что половина копейки не возникает ни разу.
export function toMoney(amount) {
  return (Math.round(amount * 100) / 100).toFixed(2);
}

export function moneyToNumber(money) {
  return Number(money);
}
